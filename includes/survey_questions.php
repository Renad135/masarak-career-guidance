/**
 * إرجاع نص السؤال حسب العمود واللغة
 * إن لم يكن العمود في القائمة يُرجع الاسم بعد استبدال _ بمسافة
 */
function getSurveyQuestionLabel($col, $lang) {
    global $survey_questions;
    $col = trim($col);
    if (isset($survey_questions[$col][$lang])) {
        return $survey_questions[$col][$lang];
    }
    return str_replace('_', ' ', $col);
}
